#!/usr/bin/env node
/**
 * Builds assets/css/style.css from the files in assets/css/src/.
 *
 * No dependencies: only Node.js is needed.
 *     node build.js
 *
 * Optional minified copy (needs internet once, via npx):
 *     npx esbuild assets/css/style.css --minify --outfile=assets/css/style.min.css
 *
 * To add a component: create assets/css/src/components/<name>.css and add it
 * to the ORDER list below.
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'assets', 'css', 'src');
const OUT = path.join(__dirname, 'assets', 'css', 'style.css');

// Order matters: tokens first, base second, components last.
const ORDER = [
  '00-tokens.css',
  '01-base.css',
  'components/button.css',
  'components/icon-button.css',
  'components/forms.css',
  'components/badge.css',
  'components/avatar.css',
  'components/rating.css',
  'components/skeleton.css',
  'components/tabs.css',
  'components/layout.css',
  'components/header.css',
  'components/footer.css',
  'components/overlays.css',
  'components/property-card.css',
  'components/property-gallery.css',
  'components/search.css',
  'components/property-details.css',
  'components/agent-card.css',
  'components/hero.css',
  'components/sections.css',
  'components/global.css',
  'components/pages.css',
  'components/location-card.css',
];

const banner = `/*!
 * Real Estate Template: main stylesheet
 * Built from assets/css/src/. Do not edit this file directly; edit the
 * source files and run "node build.js".
 * Requires Bootstrap 5.3 (load bootstrap.min.css BEFORE this file).
 */
`;

const parts = ORDER.map((file) => {
  const full = path.join(SRC, file);
  if (!fs.existsSync(full)) {
    console.error('Missing source file: ' + file);
    process.exit(1);
  }
  return fs.readFileSync(full, 'utf8').trim();
});

fs.writeFileSync(OUT, banner + '\n' + parts.join('\n\n') + '\n');
console.log('Built ' + path.relative(__dirname, OUT) + ' from ' + ORDER.length + ' source files.');
